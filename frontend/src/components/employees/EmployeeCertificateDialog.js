"use client";

import { useCallback, useEffect, useState } from "react";
import Button from "@/components/shared/Button";
import A4DocumentPreview from "@/components/shared/A4DocumentPreview";
import TextAreaField from "@/components/shared/TextAreaField";
import useFormErrors from "@/components/shared/useFormErrors";
import Dialog from "@/components/ui/Dialog";
import { downloadEmployeeCertificate, previewEmployeeCertificate } from "@/services/hrm/employees.service";

const DUTIES_LIMIT = 2000;
const errorMessage = (error, fallback) => error?.data?.message || error?.message || fallback;

/*
 * The certificates Employee Repository → Administration → ⋮ → Generate draws. `asksDuties`: the
 * experience certificate asks for the brief summary of their duties, the one thing the record does not
 * hold - optional, and left empty that line is left out; the employment certificate needs nothing and opens straight on the sheet.
 */
export const EMPLOYEE_CERTIFICATES = {
  experience: { label: "Experience Certificate", asksDuties: true },
  employment: { label: "Employment Certificate", asksDuties: false },
};

/**
 * One certificate for one employee, generated by the server: filled from their record (Mr. or Ms. by
 * gender, name, designation, department, joining date, and for experience the last working date) and
 * from that certificate's Settings → Employee → Certificate section, on an A4 sheet with Download PDF.
 *
 * Experience first asks for the summary of duties, and Edit summary goes back to it; Employment
 * generates the moment it opens.
 */
export default function EmployeeCertificateDialog({ employee, kind, onClose, onNotice }) {
  const certificate = EMPLOYEE_CERTIFICATES[kind];
  const [duties, setDuties] = useState("");
  const [html, setHtml] = useState("");
  // What the certificate's Settings section has not been given yet, as the server says.
  const [missing, setMissing] = useState([]);
  const [busy, setBusy] = useState(certificate.asksDuties ? "" : "preview");
  const [error, setError] = useState("");
  const fields = useFormErrors();
  const name = employee?.employeeName || "this employee";
  const body = useCallback(() => (certificate.asksDuties ? { duties: duties.trim() } : {}), [certificate.asksDuties, duties]);

  const preview = useCallback(async () => {
    setBusy("preview");
    setError("");
    try {
      const response = await previewEmployeeCertificate(employee.id, kind, body());
      setHtml(response?.data?.html || "");
      setMissing(Array.isArray(response?.data?.missing) ? response.data.missing : []);
    } catch (requestError) {
      // A summary the server refused is marked under its box.
      if (certificate.asksDuties && fields.fromServer(requestError)) return;
      setError(errorMessage(requestError, `Unable to generate the ${certificate.label.toLowerCase()}.`));
    } finally {
      setBusy("");
    }
  }, [body, certificate.asksDuties, certificate.label, employee.id, fields, kind]);

  // Nothing to ask for the employment certificate: it is generated as the dialog opens.
  useEffect(() => {
    if (certificate.asksDuties) return undefined;
    const timer = window.setTimeout(() => { void preview(); }, 0);
    return () => window.clearTimeout(timer);
    // Once, on opening.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function download() {
    if (busy) return;
    setBusy("download");
    setError("");
    try {
      await downloadEmployeeCertificate(employee.id, kind, body(), name, certificate.label);
      onNotice?.(`${certificate.label} for ${name} downloaded.`);
    } catch (requestError) {
      setError(errorMessage(requestError, `Unable to download the ${certificate.label.toLowerCase()}.`));
    } finally {
      setBusy("");
    }
  }

  const previewing = Boolean(html);
  const asking = certificate.asksDuties && !previewing;
  return <Dialog
    title={certificate.label}
    description={previewing ? `${name}'s ${certificate.label.toLowerCase()}, as it will print.` : `For ${name}. Their details are filled from the employee record.`}
    size={asking ? "md" : "xl"}
    busy={Boolean(busy)}
    onClose={busy ? undefined : onClose}
    footer={asking ? <>
      <Button type="button" disabled={Boolean(busy)} onClick={onClose}>Cancel</Button>
      <Button type="button" variant="primary" busy={busy === "preview"} busyLabel="Generating..." disabled={Boolean(busy)} onClick={() => void preview()}>Generate</Button>
    </> : <>
      {certificate.asksDuties
        ? <Button type="button" disabled={Boolean(busy)} onClick={() => { setHtml(""); setError(""); }}>Edit summary</Button>
        : <Button type="button" disabled={Boolean(busy)} onClick={onClose}>Close</Button>}
      {!certificate.asksDuties && !previewing && error && <Button type="button" disabled={Boolean(busy)} onClick={() => void preview()}>Try again</Button>}
      <Button type="button" variant="primary" busy={busy === "download"} busyLabel="Preparing PDF..." disabled={Boolean(busy) || !previewing} onClick={() => void download()}>Download PDF</Button>
    </>}
  >
    <div className="space-y-3 pb-2">
      {error && <p role="alert" className="rounded-md border border-red-200 bg-red-50 px-3 py-2 text-sm text-red-700">{error}</p>}
      {previewing && missing.length > 0 && <p className="rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-sm text-amber-800">
        Not set yet: {missing.join(", ")}. The certificate prints a blank in their place - add them in Settings → Employee → Certificate.
      </p>}
      {previewing && <p className="text-xs text-slate-500 md:hidden">The sheet is shrunk to fit this screen - the PDF is full size.</p>}
      {!certificate.asksDuties && !previewing && busy === "preview" && <p className="text-sm text-slate-600" aria-live="polite">Generating the certificate...</p>}
      {previewing && <A4DocumentPreview html={html} title={`${certificate.label} for ${name}`} />}
      {asking && <>
        <TextAreaField
          label="Brief summary of their duties"
          helperText="Optional. The work they did here, printed after “During this period, the employee was responsible for”; left empty, that line is left out."
          rows={6}
          maxLength={DUTIES_LIMIT}
          value={duties}
          disabled={Boolean(busy)}
          placeholder="e.g. covering weddings and events as a lead photographer, editing and delivering client albums"
          onChange={(event) => { setDuties(event.target.value); fields.clear("duties"); }}
          error={fields.errors.duties}
        />
      </>}
    </div>
  </Dialog>;
}
