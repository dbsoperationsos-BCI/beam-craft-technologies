"use client";

import { useCallback, useEffect, useState } from "react";
import ContentCopy from "@mui/icons-material/ContentCopy";
import OpenInNew from "@mui/icons-material/OpenInNew";
import QrCode2 from "@mui/icons-material/QrCode2";
import WhatsApp from "@mui/icons-material/WhatsApp";
import Button from "@/components/shared/Button";
import HelpTip from "@/components/shared/HelpTip";
import Loader from "@/components/shared/Loader";
import useWhatsappSender from "@/components/shared/useWhatsappSender";
import ShareableMessage from "@/components/shared/ShareableMessage";
import { copyToClipboard } from "@/lib/clipboard";
import { getSignatureAlbumShare, sendSignatureAlbumToGroup } from "@/services/image-selection/signature-album.service";
import { optionLabel, THEME_OPTIONS } from "@/lib/signatureAlbum.mjs";
import PublishPanel from "./PublishPanel";

/**
 * Review & Share: the album's headline, its link, PIN and expiry, and the ways it leaves - Copy
 * Link, WhatsApp (the studio's own chat with the client, or the project's linked group from the
 * signed-in person's WhatsApp), the QR of the link alone, and Open Album. Shown inside the rail's
 * Review & Share dialog. Everything but reading needs `canWrite`.
 */
export default function SharePanel({ album, canWrite, busy, onPublish, onUnpublish, onNotice, refreshKey = 0 }) {
  const [share, setShare] = useState(null);
  const [error, setError] = useState("");
  const [showQr, setShowQr] = useState(false);
  const [sending, setSending] = useState(false);
  // Send to Group goes from this person's own WhatsApp, so it is absent until that is linked.
  const { canSend } = useWhatsappSender();
  const published = album.status === "PUBLISHED";

  const load = useCallback(async () => {
    try { setShare((await getSignatureAlbumShare(album.id)).data); setError(""); }
    catch (failure) { setError(failure.message || "Unable to prepare the album for sharing."); }
  }, [album.id]);
  useEffect(() => { const timer = window.setTimeout(load, 0); return () => window.clearTimeout(timer); }, [load, album.status, album.link.shortCode, album.link.pin, album.expiresAt, refreshKey]);

  async function copy(value, label) {
    if (await copyToClipboard(value)) onNotice?.(`${label} copied.`, "success"); else onNotice?.(`Unable to copy the ${label.toLowerCase()}. Select it and copy by hand.`, "error");
  }
  function sendToClient() {
    if (!share?.whatsappShareUrl) { onNotice?.("The client's WhatsApp number is not recorded on this project.", "error"); return; }
    window.open(`${share.whatsappShareUrl}?text=${encodeURIComponent(share.message)}`, "_blank", "noopener,noreferrer");
  }
  async function sendToGroup() {
    setSending(true);
    try { const response = await sendSignatureAlbumToGroup(album.id); onNotice?.(`Sent to ${response.data.groupSubject || "the WhatsApp group"}.`, "success"); }
    catch (failure) { onNotice?.(failure.message || "Unable to send to the WhatsApp group.", "error"); }
    finally { setSending(false); }
  }

  return <div className="space-y-4">
    <section className="rounded-xl border border-slate-200 bg-white p-4 sm:p-5">
      <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500">{published ? "Signature Album Ready" : "Signature Album"}</p>
      <h3 className="mt-1 text-lg font-semibold text-slate-900">{album.title}</h3>
      <p className="mt-1 text-xs text-slate-500">{album.counts.photoCount} photos · {album.counts.chapterCount} chapter{album.counts.chapterCount === 1 ? "" : "s"} · {optionLabel(THEME_OPTIONS, album.design.theme)} theme</p>
      <div className="mt-4"><PublishPanel album={album} canWrite={canWrite} busy={busy} onPublish={onPublish} onUnpublish={onUnpublish} compact /></div>
    </section>
    <section className="rounded-xl border border-slate-200 bg-white p-4 sm:p-5">
      {error && <p role="alert" className="mb-3 rounded-md bg-red-50 px-3 py-2 text-xs text-red-700">{error}</p>}
      {!share ? <Loader label="Preparing..." size="sm" inline /> : <>
        <dl className="grid gap-3 sm:grid-cols-3">
          <div className="min-w-0"><dt className="flex items-center text-[10px] font-bold text-slate-700">Client Link<HelpTip text="The web address the client opens to view this album; it is created when the album is first published." /></dt><dd className="mt-1 flex items-center gap-1"><span className="min-w-0 flex-1 truncate text-xs text-blue-600">{share.clientUrl || "Publish to create the link"}</span>{share.clientUrl && <button type="button" onClick={() => copy(share.clientUrl, "Link")} aria-label="Copy client link" className="p-1 text-slate-500 hover:text-slate-800"><ContentCopy style={{ fontSize: 14 }} /></button>}</dd></div>
          <div><dt className="flex items-center text-[10px] font-bold text-slate-700">PIN<HelpTip text="The code the client types to open the album, generated by the system. Shown only when Require PIN is on." /></dt><dd className="mt-1 flex items-center gap-1 font-mono text-sm">{share.requiresPin ? (share.pin || "—") : <span className="text-xs font-sans text-slate-500">Not required</span>}{share.pin && <button type="button" onClick={() => copy(share.pin, "PIN")} aria-label="Copy PIN" className="p-1 text-slate-500 hover:text-slate-800"><ContentCopy style={{ fontSize: 14 }} /></button>}</dd></div>
          <div><dt className="flex items-center text-[10px] font-bold text-slate-700">Expiry<HelpTip text="The day the client link stops working. Set in the album's Expiry field, or from the default expiry when first published." /></dt><dd className="mt-1 text-xs text-slate-700">{share.expiresAtLabel || "—"}</dd></div>
        </dl>
        <div className="mt-4 flex flex-wrap gap-2">
          <Button type="button" size="sm" onClick={() => copy(share.clientUrl, "Link")} disabled={!share.clientUrl}><ContentCopy style={{ fontSize: 15 }} aria-hidden="true" /> Copy Link</Button>
          {canWrite && <Button type="button" size="sm" onClick={sendToClient} disabled={!published || !share.clientUrl} className="!border-green-200 !text-green-700"><WhatsApp style={{ fontSize: 15 }} aria-hidden="true" /> WhatsApp</Button>}
          {canWrite && canSend && share.whatsappGroupSubject && <Button type="button" size="sm" busy={sending} busyLabel="Sending..." onClick={sendToGroup} disabled={!published} className="!border-green-200 !text-green-700"><WhatsApp style={{ fontSize: 15 }} aria-hidden="true" /> Send to Group</Button>}
          <Button type="button" size="sm" onClick={() => setShowQr((value) => !value)} disabled={!share.qrDataUrl} aria-pressed={showQr}><QrCode2 style={{ fontSize: 15 }} aria-hidden="true" /> QR Code</Button>
          {share.clientUrl && published && <a href={share.clientUrl} target="_blank" rel="noreferrer" className="inline-flex min-h-9 items-center gap-1 rounded-md border border-slate-300 bg-white px-3 py-1.5 text-sm text-slate-700 hover:bg-slate-50"><OpenInNew style={{ fontSize: 15 }} aria-hidden="true" /> Open Album</a>}
        </div>
        {!published && <p className="mt-2 text-[11px] text-slate-500">The link answers only while the album is published.</p>}
        {showQr && share.qrDataUrl && <div className="mt-4 flex flex-col items-center gap-2 rounded-lg border border-slate-200 p-4 sm:flex-row sm:items-start">
          {/* A data URI the server drew; next/image has no loader for it. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={share.qrDataUrl} alt="QR code of the album link" width={180} height={180} className="h-44 w-44" />
          <div className="text-xs text-slate-600"><p>Scanning opens the album link. The PIN is not in the code.</p><a href={share.qrDataUrl} download={`signature-album-${album.link.shortCode || "qr"}.png`} className="mt-2 inline-block text-blue-600">Download QR</a></div>
        </div>}
        {published && share.message && <ShareableMessage label="WhatsApp message" message={share.message} rows={9} className="mt-4" />}
      </>}
    </section>
  </div>;
}
